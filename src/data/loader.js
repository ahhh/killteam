/**
 * Rule-pack, map and mission loading.
 *
 * Two sources, one code path:
 *   - bundled JSON under /data (fetched at runtime)
 *   - user-supplied JSON (file drop or paste), which stays in the browser
 *
 * Imported packs are parsed as data and validated before use. Nothing here
 * fetches remote JavaScript or evaluates pack content (§34).
 */
import { validateTeamPack, validateMap, validateMission, isStale, dataAgeDays } from './validators.js';
import { LIMITS, SUPPORT_LEVELS, sanitizeText } from './schema.js';

export class DataLoadError extends Error {
  constructor(message, report) {
    super(message);
    this.name = 'DataLoadError';
    this.report = report;
  }
}

async function fetchJson(url) {
  const res = await fetch(url, { cache: 'no-cache' });
  if (!res.ok) throw new DataLoadError(`Failed to load ${url}: ${res.status} ${res.statusText}`);
  return res.json();
}

export class DataRepository {
  constructor({ baseUrl = './data' } = {}) {
    this.baseUrl = baseUrl;
    this.factions = null;
    this.teams = new Map();     // id -> pack
    this.maps = new Map();
    this.missions = new Map();
    this.reports = new Map();   // id -> validation report
    this.customTeams = new Set(); // ids the user supplied locally
    this.reference = null;
    this.teamIndex = new Map(); // id -> picker fields, without the whole pack
    this.mapIndex = new Map();  // …and the same for maps
  }

  async loadCatalogue() {
    this.factions = await fetchJson(`${this.baseUrl}/factions.json`);
    return this.factions;
  }

  /**
   * The picker's index: a name, faction and support level for every bundled
   * team, at 1/175th the size of the packs they came from.
   *
   * The team picker needs those three fields for all 64 teams and the rest of
   * a pack only for the team a player actually selected, so the index is
   * fetched at boot and the packs on selection. Generated by
   * `tools/make-team-index.mjs`.
   */
  async loadIndex() {
    const [teams, maps] = await Promise.all([
      fetchJson(`${this.baseUrl}/team-index.json`),
      fetchJson(`${this.baseUrl}/map-index.json`).catch(() => null),
    ]);
    for (const [id, entry] of Object.entries(teams?.teams ?? {})) {
      this.teamIndex.set(id, entry);
    }
    for (const [id, entry] of Object.entries(maps?.maps ?? {})) {
      this.mapIndex.set(id, entry);
    }
    return this.teamIndex;
  }

  /**
   * What the map picker knows about a map before its terrain is fetched.
   * A loaded map answers for itself, so an imported one needs no index.
   */
  mapEntry(id) {
    const map = this.maps.get(id);
    if (map) return { id: map.id, name: map.name ?? map.id, blurb: map.blurb };
    return this.mapIndex.get(id) ?? null;
  }

  knowsMap(id) {
    return this.maps.has(id) || this.mapIndex.has(id);
  }

  /**
   * What the picker knows about a team before its pack is fetched.
   *
   * A loaded pack answers for itself — an imported pack is never in the
   * generated index, and a bundled one that has since been fetched carries
   * fresher fields than the index does.
   */
  teamEntry(id) {
    const pack = this.teams.get(id);
    if (pack) {
      return {
        id: pack.id,
        displayName: pack.displayName ?? pack.id,
        factionId: pack.factionId ?? null,
        supportLevel: pack.supportLevel ?? 0,
        variantOf: pack.variantOf,
        variantOfName: pack.variantOfName,
      };
    }
    return this.teamIndex.get(id) ?? null;
  }

  /** Every team id the picker can offer, whether or not its pack is loaded. */
  knownTeamIds() {
    return [...new Set([
      ...this.catalogueTeamIds(),
      ...this.teamIndex.keys(),
      ...this.teams.keys(),
    ])];
  }

  /** True if `id` names a team we could load, loaded or not. */
  knowsTeam(id) {
    return this.teams.has(id) || this.teamIndex.has(id);
  }

  /**
   * The reference catalogue names real teams and links to their official
   * source. It carries no stats by design — see data/reference-teams.json.
   */
  async loadReference() {
    try {
      this.reference = await fetchJson(`${this.baseUrl}/reference-teams.json`);
    } catch {
      this.reference = null; // Optional file; the app works without it.
    }
    return this.reference;
  }

  /** Every team id referenced by the catalogue. */
  catalogueTeamIds() {
    return (this.factions?.factions || []).flatMap((f) => f.teams || []);
  }

  async loadTeam(id) {
    if (this.teams.has(id)) return this.teams.get(id);
    const pack = await fetchJson(`${this.baseUrl}/teams/${id}.json`);
    return this.registerTeam(pack, { source: 'bundled' });
  }

  async loadMap(id) {
    if (this.maps.has(id)) return this.maps.get(id);
    const map = await fetchJson(`${this.baseUrl}/maps/${id}.json`);
    return this.registerMap(map);
  }

  async loadMission(id) {
    if (this.missions.has(id)) return this.missions.get(id);
    const mission = await fetchJson(`${this.baseUrl}/missions/${id}.json`);
    return this.registerMission(mission);
  }

  /**
   * Load many ids of one kind at once.
   *
   * The fetches overlap; the registrations do not. Loading the bundled data
   * one `await` at a time cost one round trip per file, which is most of the
   * wait before the setup screen paints. But `this.maps` is iterated directly
   * to build the map picker, so registering in *completion* order would
   * reshuffle that dropdown from one page load to the next. Fetch together,
   * register in the order asked for.
   */
  async _loadMany(ids, cache, urlFor, register) {
    const wanted = ids.filter((id) => !cache.has(id));
    const fetched = await Promise.all(wanted.map((id) => fetchJson(urlFor(id))));
    for (const obj of fetched) register(obj);
    return ids.map((id) => cache.get(id));
  }

  loadTeams(ids) {
    return this._loadMany(ids, this.teams, (id) => `${this.baseUrl}/teams/${id}.json`,
      (pack) => this.registerTeam(pack, { source: 'bundled' }));
  }

  loadMaps(ids) {
    return this._loadMany(ids, this.maps, (id) => `${this.baseUrl}/maps/${id}.json`,
      (map) => this.registerMap(map));
  }

  loadMissions(ids) {
    return this._loadMany(ids, this.missions, (id) => `${this.baseUrl}/missions/${id}.json`,
      (mission) => this.registerMission(mission));
  }

  /**
   * Register a team pack from any origin. Throws on invalid data so a broken
   * pack can never reach the engine.
   */
  registerTeam(pack, { source = 'imported' } = {}) {
    const report = validateTeamPack(pack);
    this.reports.set(`team:${pack?.id}`, report);
    if (!report.ok) {
      throw new DataLoadError(
        `Team pack "${pack?.id ?? 'unknown'}" is invalid:\n  - ${report.errors.join('\n  - ')}`,
        report
      );
    }
    pack.displayName = sanitizeText(pack.displayName, 80);
    pack.blurb = sanitizeText(pack.blurb);
    // Flavour text is shown to the player and never read by the engine, so it
    // is scrubbed on the way in like every other displayed string. An imported
    // pack is untrusted, and `lore` is the longest string a pack can carry.
    if (pack.lore) pack.lore = sanitizeText(pack.lore, LIMITS.maxLoreLength);
    for (const op of pack.operatives || []) {
      if (op.lore) op.lore = sanitizeText(op.lore, LIMITS.maxLoreLength);
    }
    pack.origin = source;
    this.teams.set(pack.id, pack);
    if (source !== 'bundled') this.customTeams.add(pack.id);
    return pack;
  }

  registerMap(map) {
    const report = validateMap(map);
    this.reports.set(`map:${map?.id}`, report);
    if (!report.ok) {
      throw new DataLoadError(
        `Map "${map?.id ?? 'unknown'}" is invalid:\n  - ${report.errors.join('\n  - ')}`,
        report
      );
    }
    this.maps.set(map.id, map);
    return map;
  }

  registerMission(mission) {
    const report = validateMission(mission);
    this.reports.set(`mission:${mission?.id}`, report);
    if (!report.ok) {
      throw new DataLoadError(
        `Mission "${mission?.id ?? 'unknown'}" is invalid:\n  - ${report.errors.join('\n  - ')}`,
        report
      );
    }
    this.missions.set(mission.id, mission);
    return mission;
  }

  /** Parse user-supplied JSON text. Never eval — JSON.parse only. */
  importJsonText(text) {
    let parsed;
    try {
      parsed = JSON.parse(text);
    } catch (err) {
      throw new DataLoadError(`Not valid JSON: ${err.message}`);
    }
    return this.importObject(parsed);
  }

  /** Route an imported object to the right register by shape. */
  importObject(obj) {
    if (Array.isArray(obj)) {
      return obj.map((item) => this.importObject(item));
    }
    if (obj?.operatives && obj?.roster) {
      return { kind: 'team', value: this.registerTeam(obj) };
    }
    if (obj?.board && (obj?.terrain || obj?.deploymentZones)) {
      return { kind: 'map', value: this.registerMap(obj) };
    }
    if (obj?.scoring) {
      return { kind: 'mission', value: this.registerMission(obj) };
    }
    throw new DataLoadError(
      'Unrecognised file. Expected a team pack (roster + operatives), a map (board + terrain), or a mission (scoring).'
    );
  }

  reportFor(kind, id) {
    return this.reports.get(`${kind}:${id}`);
  }

  /** Display metadata for the setup screen's compatibility badge (§10). */
  badgeFor(teamId) {
    const pack = this.teams.get(teamId);
    if (!pack) return null;
    const level = SUPPORT_LEVELS[pack.supportLevel] ?? SUPPORT_LEVELS[0];
    const report = this.reportFor('team', teamId);
    return {
      level: pack.supportLevel,
      label: level.label,
      badge: this.customTeams.has(teamId) ? 'Experimental (imported)' : level.badge,
      warnings: report?.warnings ?? [],
      stale: isStale(pack),
      ageDays: dataAgeDays(pack),
      dataVersion: pack.dataVersion,
      sourceUrl: pack.source?.url || '',
      publisher: pack.source?.publisher || '',
      checkedAt: pack.source?.checkedAt || '',
    };
  }
}
